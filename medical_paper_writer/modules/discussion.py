"""
Discussion and Conclusion section generator.
"""

from typing import Dict, List, Optional
from dataclasses import dataclass


@dataclass
class DiscussionPoint:
    topic: str
    content: str
    references_needed: bool = True


def generate_discussion_structure(
    study_type: str,
    pico: Dict,
    main_findings: List[str],
    secondary_findings: List[str] = None
) -> str:
    """Generate a structured discussion section."""

    findings_text = "\n".join([f"- {finding}" for finding in main_findings])
    secondary_text = ""
    if secondary_findings:
        secondary_text = "\n".join([f"- {finding}" for finding in secondary_findings])

    discussion = f"""
## Обсуждение

### Основные результаты

В настоящем исследовании изучалось влияние {pico.get('intervention', '[вмешательства]')}
на {pico.get('outcome_primary', '[исход]')} у пациентов с {pico.get('population', '[состояние]')}.

Основные полученные результаты:
{findings_text}

{f'''Дополнительно было установлено:
{secondary_text}
''' if secondary_text else ''}

### Сопоставление с литературными данными

Полученные нами результаты [согласуются с / противоречат] данным предыдущих исследований.

[Автор и соавт.] в своём исследовании (n = [X]) показали, что [результаты].
Наши данные [подтверждают / расширяют / противоречат] этим находкам, что может быть объяснено
[различиями в популяции / методологии / длительности наблюдения].

В мета-анализе [Автор и соавт., год] было продемонстрировано [результаты].
Результаты нашего исследования находятся в пределах доверительных интервалов,
полученных в данном мета-анализе.

[Добавить 3-5 ссылок на релевантные исследования с обсуждением]

### Возможные механизмы

Наблюдаемый эффект {pico.get('intervention', '[вмешательства]')} может быть обусловлен
несколькими механизмами:

1. [Механизм 1]: [объяснение и ссылки]
2. [Механизм 2]: [объяснение и ссылки]
3. [Механизм 3]: [объяснение и ссылки]

### Клиническое значение

Результаты настоящего исследования имеют важное значение для клинической практики:

1. **Для диагностики/лечения**: [практические рекомендации]
2. **Для организации помощи**: [организационные аспекты]
3. **Для пациентов**: [влияние на качество жизни, прогноз]

Полученные данные могут быть использованы для [обновления клинических рекомендаций /
разработки протоколов / оптимизации терапии].

### Сильные стороны исследования

К сильным сторонам настоящего исследования следует отнести:

1. [Дизайн исследования]: {_get_strength_for_study_type(study_type)}
2. Использование валидированных методов оценки исходов
3. Достаточный размер выборки для выявления клинически значимых различий
4. [Дополнительные сильные стороны]

### Ограничения исследования

При интерпретации результатов следует учитывать ряд ограничений:

1. **Дизайн**: {_get_limitation_for_study_type(study_type)}
2. **Выборка**: [ограничения выборки — одноцентровое исследование, критерии отбора]
3. **Измерения**: [потенциальные проблемы с измерением переменных]
4. **Конфаундинг**: [неучтённые вмешивающиеся факторы]
5. **Генерализуемость**: [ограничения применимости результатов]

Данные ограничения следует учитывать при планировании будущих исследований.

### Направления дальнейших исследований

На основании полученных результатов можно определить следующие направления
для дальнейших исследований:

1. Проведение [РКИ / проспективных когортных исследований] для подтверждения результатов
2. Изучение [подгрупп пациентов / долгосрочных исходов / механизмов]
3. Оценка [экономической эффективности / безопасности / приверженности]
4. [Другие направления]
"""

    return discussion


def _get_strength_for_study_type(study_type: str) -> str:
    """Get strength description based on study type."""
    strengths = {
        "rct": "Рандомизированный контролируемый дизайн минимизирует риск систематических ошибок",
        "cohort_prospective": "Проспективный дизайн позволяет установить временную последовательность",
        "cohort_retrospective": "Использование существующих данных позволило изучить большую выборку",
        "case_control": "Дизайн случай-контроль эффективен для изучения редких исходов",
        "cross_sectional": "Одномоментный дизайн позволяет оценить распространённость",
        "systematic_review": "Систематический подход обеспечивает полноту охвата литературы",
    }
    return strengths.get(study_type, "Использованы методы, соответствующие поставленной цели")


def _get_limitation_for_study_type(study_type: str) -> str:
    """Get limitation description based on study type."""
    limitations = {
        "rct": "Строгие критерии включения могут ограничивать генерализуемость результатов",
        "cohort_prospective": "Возможно неконтролируемое вмешивающееся влияние конфаундеров",
        "cohort_retrospective": "Ретроспективный характер не позволяет исключить selection bias",
        "case_control": "Дизайн подвержен recall bias при оценке экспозиции",
        "cross_sectional": "Поперечный дизайн не позволяет установить причинно-следственную связь",
        "systematic_review": "Качество обзора ограничено качеством включённых первичных исследований",
    }
    return limitations.get(study_type, "Наблюдательный характер исследования")


def generate_conclusion(
    study_type: str,
    pico: Dict,
    main_findings: List[str],
    clinical_implications: List[str]
) -> str:
    """Generate conclusion section."""

    findings_text = " ".join(main_findings[:2])  # Use first 2 findings
    implications_text = " ".join(clinical_implications[:2]) if clinical_implications else ""

    conclusion = f"""
## Заключение

{findings_text}

{implications_text}

Полученные результаты свидетельствуют о [эффективности / целесообразности / необходимости]
применения {pico.get('intervention', '[вмешательства]')} у пациентов с {pico.get('population', '[состояние]')}.

Необходимы дальнейшие исследования для [подтверждения результатов в более широкой популяции /
оценки долгосрочных исходов / уточнения оптимальных режимов применения].
"""

    return conclusion


def generate_abstract(
    study_type: str,
    pico: Dict,
    methods_summary: str,
    results_summary: str,
    conclusion_summary: str
) -> str:
    """Generate structured abstract."""

    abstract_templates = {
        "rct": f"""
### Резюме

**Цель:** Оценить эффективность {pico.get('intervention', '[вмешательства]')}
{f"в сравнении с {pico.get('comparison', '[контролем]')}" if pico.get('comparison') else ""}
для {pico.get('outcome_primary', '[исход]')} у пациентов с {pico.get('population', '[состояние]')}.

**Материалы и методы:** {methods_summary}

**Результаты:** {results_summary}

**Заключение:** {conclusion_summary}

**Ключевые слова:** [5-7 ключевых слов]
""",

        "cohort_prospective": f"""
### Резюме

**Цель:** Изучить связь между {pico.get('intervention', '[фактором]')}
и {pico.get('outcome_primary', '[исходом]')} у {pico.get('population', '[популяция]')}.

**Материалы и методы:** {methods_summary}

**Результаты:** {results_summary}

**Заключение:** {conclusion_summary}

**Ключевые слова:** [5-7 ключевых слов]
""",

        "case_control": f"""
### Резюме

**Цель:** Оценить связь между воздействием {pico.get('intervention', '[фактора]')}
и развитием {pico.get('outcome_primary', '[заболевания/исхода]')}.

**Материалы и методы:** {methods_summary}

**Результаты:** {results_summary}

**Заключение:** {conclusion_summary}

**Ключевые слова:** [5-7 ключевых слов]
""",

        "systematic_review": f"""
### Резюме

**Цель:** Систематизировать данные об эффективности {pico.get('intervention', '[вмешательства]')}
для {pico.get('outcome_primary', '[исхода]')} у {pico.get('population', '[популяция]')}.

**Материалы и методы:** {methods_summary}

**Результаты:** {results_summary}

**Заключение:** {conclusion_summary}

**Ключевые слова:** [5-7 ключевых слов]
""",
    }

    return abstract_templates.get(study_type, abstract_templates["rct"])


