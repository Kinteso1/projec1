def get_discussion_checklist(study_type: str) -> List[str]:
    """Get checklist for discussion section."""

    common_items = [
        "✓ Резюмированы основные результаты",
        "✓ Результаты интерпретированы в контексте гипотезы",
        "✓ Проведено сопоставление с литературными данными (минимум 5 источников)",
        "✓ Обсуждены возможные механизмы",
        "✓ Описано клиническое/практическое значение",
        "✓ Перечислены сильные стороны исследования",
        "✓ Честно описаны ограничения",
        "✓ Определены направления дальнейших исследований",
        "✓ Сформулировано заключение, соответствующее цели",
    ]

    specific_items = {
        "rct": [
            "✓ Обсуждено влияние ослепления на результаты",
            "✓ Оценена применимость результатов в реальной практике",
        ],
        "cohort_prospective": [
            "✓ Обсуждено влияние потенциальных конфаундеров",
            "✓ Оценена роль time-varying exposures",
        ],
        "case_control": [
            "✓ Обсуждены recall bias и selection bias",
            "✓ Оценена репрезентативность контрольной группы",
        ],
        "systematic_review": [
            "✓ Обсуждена гетерогенность между исследованиями",
            "✓ Оценен риск публикационного смещения",
        ],
    }

    return common_items + specific_items.get(study_type, [])


def format_for_journal(
    abstract: str,
    introduction: str,
    methods: str,
    results: str,
    discussion: str,
    references: List[str],
    word_limit: Optional[int] = None
) -> str:
    """Format full manuscript for journal submission."""

    manuscript = f"""
# [НАЗВАНИЕ СТАТЬИ]

## Авторы
[Имя Фамилия]¹, [Имя Фамилия]²

¹ [Аффилиация 1]
² [Аффилиация 2]

**Автор для корреспонденции:** [Имя Фамилия], email: [email]

---

{abstract}

---

## Введение

{introduction}

## Материалы и методы

{methods}

## Результаты

{results}

{discussion}

## Благодарности

[При необходимости]

## Финансирование

[Источники финансирования или "Исследование проведено без спонсорской поддержки"]

## Конфликт интересов

Авторы заявляют об отсутствии конфликта интересов.

## Вклад авторов

[Описать вклад каждого автора по CRediT]

## Список литературы

{chr(10).join([f"{i+1}. {ref}" for i, ref in enumerate(references)])}

---

**Количество слов:** [подсчитать]
**Количество таблиц:** [X]
**Количество рисунков:** [X]
"""

    return manuscript
