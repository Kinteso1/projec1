def generate_inclusion_criteria(pico: Dict, study_type: str) -> str:
    """Generate inclusion/exclusion criteria."""

    return f"""
### Критерии включения и исключения

#### Критерии включения
1. Возраст [указать диапазон] лет
2. Подтверждённый диагноз: {pico.get('population', '[диагноз]')}
3. [Дополнительные критерии, связанные с PICO]
4. Информированное согласие на участие в исследовании

#### Критерии исключения
1. Тяжёлая сопутствующая патология: [перечислить]
2. Противопоказания к {pico.get('intervention', '[вмешательство]')}
3. Участие в других клинических исследованиях
4. Беременность или лактация (при необходимости)
5. Отказ от участия в исследовании
"""


def generate_intervention_description(intervention: str, study_type: str) -> str:
    """Generate intervention/exposure description."""

    return f"""
### Описание вмешательства

#### Основная группа
**{intervention}**
- Дозировка/интенсивность: [указать]
- Способ применения: [указать]
- Длительность: [указать]
- Частота: [указать]

#### Контрольная группа
[Описание контрольного вмешательства/плацебо/стандартной терапии]
- [Детали]

#### Сопутствующая терапия
[Описать разрешённую и запрещённую сопутствующую терапию]
"""


def generate_outcome_assessment(primary_outcome: str, secondary_outcomes: List[str]) -> str:
    """Generate outcome assessment description."""

    secondary_text = "\n".join([f"- {outcome}" for outcome in secondary_outcomes])

    return f"""
### Оценка исходов

#### Первичный исход
**{primary_outcome}**
- Метод измерения: [описать инструмент/шкалу]
- Временные точки: [указать]
- Определение события: [для бинарных исходов]
- Минимальная клинически значимая разница: [указать]

#### Вторичные исходы
{secondary_text}

#### Безопасность
- Регистрация всех нежелательных явлений
- Классификация тяжести: [шкала]
- Серьёзные нежелательные явления: [определение]
"""


def generate_statistical_analysis(
    primary_outcome: str,
    outcome_type: str,
    study_type: str,
    sample_size_info: Optional[Dict] = None
) -> str:
    """Generate statistical analysis plan."""

    sample_size_text = ""
    if sample_size_info:
        sample_size_text = f"""
#### Расчёт размера выборки
{sample_size_info.get('recommendation', '')}
Параметры расчёта:
- Мощность: {sample_size_info.get('power', 0.8) * 100}%
- Уровень значимости: {sample_size_info.get('alpha', 0.05)}
- {sample_size_info.get('formula_description', '')}
"""

    analysis_methods = {
        "continuous": """
#### Анализ непрерывных переменных
- Описательная статистика: среднее ± стандартное отклонение (при нормальном распределении)
  или медиана [межквартильный размах] (при ненормальном)
- Проверка нормальности: критерий Шапиро-Уилка
- Сравнение групп: t-критерий Стьюдента или критерий Манна-Уитни
- Множественные сравнения: поправка Бонферрони
""",
        "binary": """
#### Анализ бинарных переменных
- Описательная статистика: абсолютные и относительные частоты
- Сравнение групп: критерий хи-квадрат или точный критерий Фишера
- Оценка эффекта: отношение шансов (OR) с 95% доверительным интервалом
- Многофакторный анализ: логистическая регрессия
""",
        "time_to_event": """
#### Анализ выживаемости
- Метод Каплана-Мейера для построения кривых выживаемости
- Лог-ранк тест для сравнения групп
- Модель пропорциональных рисков Кокса для оценки HR с ковариатами
- Проверка предположения о пропорциональности рисков
""",
    }

    return f"""
### Статистический анализ

{sample_size_text}

#### Общие принципы
- Уровень статистической значимости: p < 0,05 (двусторонний)
- Анализ проводился по принципу intention-to-treat (ITT)
- Пропущенные данные: [описать метод обработки]
- Программное обеспечение: [SPSS / R / Stata / другое], версия [X]

{analysis_methods.get(outcome_type, analysis_methods['continuous'])}

#### Анализ подгрупп
[Описать запланированные анализы подгрупп и их обоснование]

#### Анализ чувствительности
[Описать запланированные анализы чувствительности]
"""


def generate_ethics_statement(study_type: str) -> str:
    """Generate ethics and consent statement."""

    return """
### Этические аспекты

Исследование проведено в соответствии с принципами Хельсинкской декларации
Всемирной медицинской ассоциации и одобрено Локальным этическим комитетом
[название учреждения] (протокол № [номер] от [дата]).

Все участники подписали информированное согласие на участие в исследовании.
[Для ретроспективных исследований]: Учитывая ретроспективный характер исследования
и использование деперсонализированных данных, информированное согласие не требовалось.

#### Конфиденциальность
Данные пациентов были деперсонализированы. Доступ к базе данных имели только
исследователи, участвующие в проекте.
"""


def generate_full_methods_section(
    study_type: str,
    pico: Dict,
    primary_outcome: str,
    secondary_outcomes: List[str],
    outcome_type: str = "continuous",
    sample_size_info: Optional[Dict] = None
) -> str:
    """Generate complete Methods section."""

    sections = [
        generate_study_design_description(study_type, pico),
        generate_inclusion_criteria(pico, study_type),
        generate_intervention_description(pico.get('intervention', ''), study_type),
        generate_outcome_assessment(primary_outcome, secondary_outcomes),
        generate_statistical_analysis(primary_outcome, outcome_type, study_type, sample_size_info),
        generate_ethics_statement(study_type),
    ]

    return "\n\n".join(sections)


